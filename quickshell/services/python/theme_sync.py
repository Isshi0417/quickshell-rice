def sync_xresources(bg, surface, current_line, fg, accent, sub_accent):
    xres_path = os.path.expanduser('~/.Xresources')
    xres_content = f"""! Auto-generated by Quickshell Theme Engine
*.background: {bg}
*.foreground: {fg}
*.cursorColor: {accent}
*.color0: {bg}
*.color1: #ff9580
*.color2: #8aff80
*.color3: #ffff80
*.color4: {accent}
*.color5: {sub_accent}
*.color6: #80ffea
*.color7: {fg}
*.color8: {current_line}
*.color9: #ff9580
*.color10: #8aff80
*.color11: #ffff80
*.color12: {accent}
*.color13: {sub_accent}
*.color14: #80ffea
*.color15: #ffffff
"""
    try:
        with open(xres_path, 'w') as f:
            f.write(xres_content)
        subprocess.run(["xrdb", "-merge", xres_path], check=False, stderr=subprocess.DEVNULL)
    except Exception:
        pass

